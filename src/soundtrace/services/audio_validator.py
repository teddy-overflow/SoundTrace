from pathlib import Path


class AudioValidator:
    """Проверяет аудиофайлы перед их обработкой."""

    # Список расширений аудиофайлов, которые поддерживает приложение.
    SUPPORTED_FORMATS = {
        ".mp3",
        ".wav",
        ".flac",
        ".ogg",
        ".m4a",
    }

    def validate(self, file_path: str) -> tuple[bool, str]:
        """Проверяет существование файла, его тип, формат и размер."""

        # Преобразуем строковый путь в объект Path для работы с файловой системой.
        path = Path(file_path)

        # Проверяем, существует ли файл по указанному пути.
        if not path.exists():
            return False, "Файл не найден."

        # Убеждаемся, что указанный путь ведёт именно к файлу, а не к папке.
        if not path.is_file():
            return False, "Указанный путь не является файлом."

        # Проверяем, что файл не пустой.
        if path.stat().st_size == 0:
            return False, "Файл пуст."

        # Получаем расширение файла и приводим его к нижнему регистру.
        # Это позволяет одинаково обрабатывать .MP3 и .mp3.
        if path.suffix.lower() not in self.SUPPORTED_FORMATS:
            return False, "Неподдерживаемый формат аудиофайла."

        # Если все проверки пройдены, файл считается допустимым.
        return True, "Файл прошёл проверку."